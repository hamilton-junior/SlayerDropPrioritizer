package net.runelite.client.plugins.slayerdropprioritizer;

/**
 * Which part of a ground item menu entry the highlight color is applied to.
 */
public enum HighlightPart {
    /** Color only the option (e.g. "Take"). */
    OPTION,
    /** Color only the item name. */
    NAME,
    /** Color both the option and the item name. */
    BOTH
}
